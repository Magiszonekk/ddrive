// ddrive — Server-rendered /login entry page (thin SEO shell).
//
// This page is a thin entry into the SPA at /app/login — not a target for
// organic search traffic (that lives on /). It exists so that:
//   - branded "ddrive login" searches can land here with a clear CTA,
//   - links from external sites (e.g. GitHub README "Sign in" link) point
//     to a stable, non-SPA URL that explains the page in 5 lines.
//
// To avoid competing with the canonical landing page in search rankings:
//   - noindex, follow: this page is not in the index, but links from it
//     still pass link equity to other pages on the site.
//   - canonical: /  — search engines that see this URL consolidate the
//     signal to the main landing page instead of treating it as duplicate.
//   - no JSON-LD / FAQ / structured data — keep the page light.

