export async function handleLoginPage(req: Request): Promise<Response> {
  const title = META.title;
  const metaTags = renderMetaTags(req, META);
  // Override canonical to point at the main landing page so this thin
  // entry page never competes in SERPs. og:url and the path-derived
  // canonical generated by renderMetaTags are both replaced by the same
  // single tag below. publicOrigin honors X-Forwarded-Proto so this is
  // https:// in production (where TLS terminates at nginx).
  const canonicalHref = `${publicOrigin(req)}/`;
  const cleanedMetaTags = metaTags
    .split("\n")
    .filter((line) => !line.includes('rel="canonical"') && !line.includes('property="og:url"'))
    .join("\n");
  const canonicalTags = [
    `<link rel="canonical" href="${escapeHtml(canonicalHref)}" />`,
    `<meta property="og:url" content="${escapeHtml(canonicalHref)}" />`,
  ].join("\n");

  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${escapeHtml(title)}</title>
${cleanedMetaTags}
${canonicalTags}
${STYLE}
</head>
<body>
${BODY_HTML}
</body>
</html>`;

  return new Response(html, {
    status: 200,
    headers: {
      "Content-Type": "text/html; charset=utf-8",
      "Cache-Control": "public, max-age=300, s-maxage=3600",
    },
  });
}
